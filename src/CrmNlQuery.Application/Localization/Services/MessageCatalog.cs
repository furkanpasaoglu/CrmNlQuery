    /// <summary>
    /// Returns the message dictionary for a language.
    /// </summary>
    public static IReadOnlyDictionary<string, string> For(string language)
        => UiLanguage.Parse(language) == UiLanguage.Turkish ? Tr : En;

    public static IReadOnlyCollection<string> Keys => En.Keys.ToList();

    /// <summary>
    /// Renders a message in the request's language through a short path, using the language resolved by the HTTP middleware.
    /// </summary>
    public static string Now(string key, IReadOnlyDictionary<string, string>? args = null) => Render(key, RequestLanguage.Current, args);

    /// <summary>
    /// Builds the named-argument dictionary for message rendering.
    /// </summary>
    public static IReadOnlyDictionary<string, string> Args(params (string Name, string Value)[] pairs) => pairs.ToDictionary(p => p.Name, p => p.Value);

    /// <summary>
    /// Translates a key to a language and fills {name} parameters, falling back to English for unknown keys.
    /// </summary>
    public static string Render(string key, string language, IReadOnlyDictionary<string, string>? args = null)
    {
        var table = For(language);
        if (!table.TryGetValue(key, out var text) && !En.TryGetValue(key, out text))
        {
            return key;
        }
        if (args is null || args.Count == 0)
        {
            return text;
        }
        foreach (var (name, value) in args)
        {
            text = text.Replace("{" + name + "}", value, StringComparison.Ordinal);
        }
        return text;
    }
